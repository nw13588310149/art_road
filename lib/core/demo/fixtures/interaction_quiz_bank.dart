import '../media/demo_media.dart';

/// 美术常识题库中的一道单选题。
class DemoQuizQuestion {
  const DemoQuizQuestion(
    this.id,
    this.category,
    this.stem,
    this.options,
    this.answer,
    this.parse, {
    this.image = '',
    this.imageWidth = 0,
    this.imageHeight = 0,
  });

  final int id;
  final String category;
  final String stem;
  final List<String> options;

  /// 正确选项下标：0=A … 3=D。
  final int answer;
  final String parse;

  /// 题干配图（`asset:` 引用），空串表示纯文字题。
  final String image;
  final int imageWidth;
  final int imageHeight;

  String get questionHtml {
    final text = '<p>【$category】$stem</p>';
    if (image.isEmpty) {
      return text;
    }
    final url = DemoMedia.url(image);
    return '$text<p><img src="$url" width="$imageWidth" height="$imageHeight"/></p>';
  }

  String get parseHtml => '<p>$parse</p>';
}

